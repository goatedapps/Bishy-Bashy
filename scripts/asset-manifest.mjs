import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { AUDIO_FILES } from './audio/score.js';
import { ARCADE_AUDIO_FILES } from './audio/arcade.js';
const images = JSON.parse(await readFile(new URL('./image-assets.json', import.meta.url)));
const sounds = [...new Set([...Object.values(AUDIO_FILES).filter(file => file !== 'countdown.wav'), ...Object.values(ARCADE_AUDIO_FILES), 'wrong.mp3', 'Button-Press.mp3', 'Punch-button.mp3', 'how-to-play.mp3', 'Diuup.mp3', 'flip.mp3', 'dice-roll.mp3', 'countdown.mp3', 'podium-winner.mp3', 'Fireworks.mp3', 'bounce.mp3', 'Ding.mp3', 'roulette.mp3', 'Game-select.mp3', 'Background-ActionRock.mp3', 'game-instructions.mp3'])];
await mkdir(new URL('../public/audio/optimized/', import.meta.url), { recursive: true });
const assets = await Promise.all([...images, ...sounds.map(file => `audio/${file}`)].map(async path => {
  const folder = path.slice(0, path.lastIndexOf('/') + 1);
  const filename = path.slice(folder.length);
  if (!(await readdir(new URL(`../public/${folder}`, import.meta.url))).includes(filename)) throw new Error(`Asset filename must match case exactly: public/${path}`);
  const bytes = await readFile(new URL(`../public/${path}`, import.meta.url));
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
  const asset = { path, bytes: bytes.length, hash };
  if (path.endsWith('.wav')) {
    const compressed = gzipSync(bytes, { level: 9 });
    if (compressed.length < bytes.length * .95) {
      asset.compressed = `audio/optimized/${path.split('/').at(-1)}-${hash}.gz`;
      asset.downloadBytes = compressed.length;
      await writeFile(new URL(`../public/${asset.compressed}`, import.meta.url), compressed);
    }
  }
  return asset;
}));
const current = new Set(assets.map(asset => asset.compressed?.split('/').at(-1)));
for (const name of await readdir(new URL('../public/audio/optimized/', import.meta.url))) {
  if (/\.wav-[0-9a-f]{16}\.gz$/.test(name) && !current.has(name)) await unlink(new URL(`../public/audio/optimized/${name}`, import.meta.url));
}
await writeFile(new URL('../src/asset-manifest.js', import.meta.url), `// Generated by scripts/asset-manifest.mjs from the delivery files.\nexport const ASSETS = ${JSON.stringify(assets, null, 2)};\n`);
